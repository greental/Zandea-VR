    /// <summary>
    /// One-shot setup: combat SOs (if missing), core ship components, two hardpoints + group + disengage wiring.
    /// Editor-only; under MyAssets/scripts/WeaponsSystem/Editor.
    /// </summary>
    public static class ShipWeaponsSystemSetup
    {
        private const string AutoFolder = "Assets/WeaponsSystem/Data/AutoGenerated";

        private const string PathGlobal = AutoFolder + "/CombatGlobalConfig.asset";
        private const string PathShield = AutoFolder + "/ShieldZoneConfig_Default.asset";
        private const string PathModes = AutoFolder + "/ShipCombatModeConfig_Default.asset";
        private const string PathUndeploy = AutoFolder + "/UndeployDefenseConfig_Default.asset";
        private const string PathWeaponLaser = AutoFolder + "/WeaponDefinition_Laser_Default.asset";
        private const string PathWeaponKinetic = AutoFolder + "/WeaponDefinition_Kinetic_Default.asset";

        [MenuItem("GameObject/VR Koombar/Add Weapons System to Ship", false, 10)]
        private static void MenuAddToSelection()
        {
            GameObject root = Selection.activeGameObject;
            if (root == null)
            {
                EditorUtility.DisplayDialog("Weapons Setup", "Select your ship root GameObject first.", "OK");
                return;
            }

            ApplyToShip(root);
        }

        [MenuItem("GameObject/VR Koombar/Add Weapons System to Ship", true)]
        private static bool MenuValidate()
        {
            return Selection.activeGameObject != null;
        }

        /// <summary>Public entry for custom inspectors.</summary>
        public static void ApplyToShip(GameObject shipRoot)
        {
            if (shipRoot == null)
            {
                return;
            }

            Undo.RegisterCompleteObjectUndo(shipRoot, "Add Weapons System");

            EnsureFolderExists(AutoFolder);

            CombatGlobalConfig global = GetOrCreateAsset(PathGlobal, CreateDefaultGlobal);
            ShieldZoneConfig shieldCfg = GetOrCreateAsset(PathShield, CreateDefaultShield);
            ShipCombatModeConfig modes = GetOrCreateAsset(PathModes, CreateDefaultModes);
            UndeployDefenseConfig undeploy = GetOrCreateAsset(PathUndeploy, () => ScriptableObject.CreateInstance<UndeployDefenseConfig>());
            WeaponDefinition laserDef = GetOrCreateAsset(PathWeaponLaser, () => CreateWeaponDef("laser_primary", DamageType.Laser, 12f, 8, 0.25f, 1.2f, 4f));
            WeaponDefinition kineticDef = GetOrCreateAsset(PathWeaponKinetic, () => CreateWeaponDef("kinetic_secondary", DamageType.Kinetic, 6f, 14, 0.35f, 0.15f, 18f));

            var shield = GetOrAddComponent<ShieldSystem>(shipRoot);
            var subsystem = GetOrAddComponent<SubsystemController>(shipRoot);
            var damageable = GetOrAddComponent<CombatDamageable>(shipRoot);
            var modeCtrl = GetOrAddComponent<ShipCombatModeController>(shipRoot);
            var groups = GetOrAddComponent<WeaponGroupController>(shipRoot);
            var disengage = GetOrAddComponent<DefensiveDisengageController>(shipRoot);

            Undo.RegisterCompleteObjectUndo(shield, "Configure Shield");
            Undo.RegisterCompleteObjectUndo(damageable, "Configure Damageable");
            Undo.RegisterCompleteObjectUndo(modeCtrl, "Configure Modes");
            Undo.RegisterCompleteObjectUndo(disengage, "Configure Disengage");

            SetPrivate(shield, "shieldConfig", shieldCfg);
            SetPrivate(shield, "verboseLogs", false);

            SetPrivate(damageable, "globalConfig", global);
            SetPrivate(damageable, "shieldSystem", shield);
            SetPrivate(damageable, "subsystemController", subsystem);
            SetPrivate(damageable, "maxHull", 100f);
            SetPrivate(damageable, "combatDisabledHullThreshold", 20f);
            SetPrivate(damageable, "verboseLogs", false);

            SetPrivate(modeCtrl, "modeConfig", modes);
            SetPrivate(modeCtrl, "defaultMode", CombatMode.Tanky);

            Transform mountTransform = ResolveWeaponsMountTransform(shipRoot.transform);
            if (mountTransform.GetComponent<Rigidbody>() == null)
            {
                Debug.LogWarning(
                    "[ShipWeaponsSystemSetup] No Rigidbody on the selected ship or its children. " +
                    "Weapons are parented to the selection; add a Rigidbody on the physics root so guns move with the ship.",
                    shipRoot);
            }

            Transform weaponsRoot = mountTransform.Find("Weapons");
            if (weaponsRoot == null)
            {
                weaponsRoot = shipRoot.transform.Find("Weapons");
            }

            if (weaponsRoot != null && weaponsRoot.parent != mountTransform)
            {
                Undo.RecordObject(weaponsRoot, "Parent Weapons under Rigidbody");
                weaponsRoot.SetParent(mountTransform, true);
            }

            if (weaponsRoot == null)
            {
                GameObject wr = new GameObject("Weapons");
                Undo.RegisterCreatedObjectUndo(wr, "Weapons root");
                wr.transform.SetParent(mountTransform, false);
                weaponsRoot = wr.transform;
            }

            WeaponHardpoint hpPrimary = EnsureHardpoint(weaponsRoot, "Hardpoint_Primary", undeploy, out WeaponController wPrimary, laserDef);
            WeaponHardpoint hpSecondary = EnsureHardpoint(weaponsRoot, "Hardpoint_Secondary", undeploy, out WeaponController wSecondary, kineticDef);

            SerializedObject soDisengage = new SerializedObject(disengage);
            soDisengage.FindProperty("config").objectReferenceValue = undeploy;
            soDisengage.FindProperty("damageable").objectReferenceValue = damageable;
            soDisengage.FindProperty("verboseLogs").boolValue = false;
            soDisengage.FindProperty("hardpoints").SetArray(new Object[] { hpPrimary, hpSecondary });
            soDisengage.ApplyModifiedPropertiesWithoutUndo();

            SerializedObject soGroups = new SerializedObject(groups);
            soGroups.FindProperty("primaryWeapons").SetArray(new[] { wPrimary });
            soGroups.FindProperty("secondaryWeapons").SetArray(new[] { wSecondary });
            soGroups.ApplyModifiedPropertiesWithoutUndo();

            ShipWeaponsOrchestrator orchestrator = GetOrAddComponent<ShipWeaponsOrchestrator>(shipRoot);
            Undo.RegisterCompleteObjectUndo(orchestrator, "ShipWeaponsOrchestrator");
            SerializedObject soOrch = new SerializedObject(orchestrator);
            soOrch.FindProperty("weaponGroups").objectReferenceValue = groups;
            SerializedProperty hpProp = soOrch.FindProperty("hardpoints");
            if (hpProp != null)
            {
                hpProp.SetArray(new Object[] { hpPrimary, hpSecondary });
            }

            soOrch.FindProperty("sitInCockpit").objectReferenceValue =
                shipRoot.GetComponentInChildren<SitInCockpit>(true);
            soOrch.FindProperty("pilotJoystick").objectReferenceValue =
                shipRoot.GetComponentInChildren<HOTASJoystick>(true);
#if ENABLE_INPUT_SYSTEM
            SerializedProperty trig = soOrch.FindProperty("fireTriggerAction");
            if (trig != null)
            {
                trig.objectReferenceValue = null;
            }
#endif
            soOrch.FindProperty("joystickTriggerFireEnabled").boolValue = true;
            soOrch.FindProperty("triggerPressThreshold").floatValue = 0.35f;
            soOrch.FindProperty("verboseLogs").boolValue = false;
            soOrch.ApplyModifiedPropertiesWithoutUndo();

            EditorUtility.SetDirty(shipRoot);
            EditorUtility.SetDirty(shield);
            EditorUtility.SetDirty(damageable);
            AssetDatabase.SaveAssets();

            Debug.Log(
                $"[ShipWeaponsSystemSetup] Weapons stack added to '{shipRoot.name}'. " +
                $"Assign projectile prefabs on '{PathWeaponLaser}' and '{PathWeaponKinetic}'. " +
                $"Add ShipWeaponsOrchestrator → Fire Trigger Action (Right Hand Trigger). " +
                $"Use orchestrator for deploy toggles, weapon group, and trigger fire.",
                shipRoot);
        }

        /// <summary>
        /// Parent hardpoints under the same transform as the ship <see cref="Rigidbody"/> so they are not left
        /// under a visual-only root (guns would not follow physics and can fall with gravity).
        /// </summary>
        private static Transform ResolveWeaponsMountTransform(Transform shipRoot)
        {
            if (shipRoot == null)
            {
                return null;
            }

            Rigidbody rb = shipRoot.GetComponent<Rigidbody>();
            if (rb == null)
            {
                rb = shipRoot.GetComponentInChildren<Rigidbody>(true);
            }

            return rb != null ? rb.transform : shipRoot;
        }

        private static CombatGlobalConfig CreateDefaultGlobal()
        {
            var g = ScriptableObject.CreateInstance<CombatGlobalConfig>();
            g.kineticVsIntactShieldMultiplier = 0.15f;
            g.missileVsIntactShieldMultiplier = 0.2f;
            g.laserVsHullMultiplier = 0.1f;
            g.logDamageRouting = false;
            g.logShieldBreaches = true;
            g.logSubsystemFailures = true;
            return g;
        }

        private static ShieldZoneConfig CreateDefaultShield()
        {
            var s = ScriptableObject.CreateInstance<ShieldZoneConfig>();
            s.consecutiveHitWindowSeconds = 1f;
            s.sameArcConsecutiveMultiplier = 1.4f;
            s.arcs = new[]
            {
                Arc(ShieldArc.Front, 100f, 2f, 8f, 3f, 2f, 24f, 3f, 2f),
                Arc(ShieldArc.Left, 85f, 2f, 7f, 3f, 2f, 22f, 3f, 2f),
                Arc(ShieldArc.Right, 85f, 2f, 7f, 3f, 2f, 22f, 3f, 2f),
                Arc(ShieldArc.Rear, 75f, 2f, 6f, 3f, 2f, 20f, 3f, 2f),
            };
            return s;
        }

        private static ArcShieldConfig Arc(
            ShieldArc arc, float cap, float delay, float rate, float instGain, float instDecay,
            float thr, float breachDur, float recovery)
        {
            return new ArcShieldConfig
            {
                arc = arc,
                capacity = cap,
                rechargeDelay = delay,
                rechargeRate = rate,
                instabilityGainPerLaserHit = instGain,
                instabilityDecayPerSecond = instDecay,
                breachThreshold = thr,
                breachDuration = breachDur,
                breachRecoverySeconds = recovery,
            };
        }

        private static ShipCombatModeConfig CreateDefaultModes()
        {
            var m = ScriptableObject.CreateInstance<ShipCombatModeConfig>();
            m.profiles = new[]
            {
                new CombatModeProfile { mode = CombatMode.Chase, enginesMultiplier = 1.2f, shieldsMultiplier = 0.85f, weaponsMultiplier = 1.15f },
                new CombatModeProfile { mode = CombatMode.Tanky, enginesMultiplier = 0.85f, shieldsMultiplier = 1.2f, weaponsMultiplier = 1.15f },
                new CombatModeProfile { mode = CombatMode.Runaway, enginesMultiplier = 1.2f, shieldsMultiplier = 1.15f, weaponsMultiplier = 0.85f },
            };
            return m;
        }

        private static WeaponDefinition CreateWeaponDef(
            string id, DamageType type, float fireRate, float speed, float heatPerShot,
            float shieldIx, float hullIx)
        {
            var w = ScriptableObject.CreateInstance<WeaponDefinition>();
            w.weaponId = id;
            w.damageType = type;
            w.projectilePrefab = null;
            w.projectileSpeed = speed;
            w.fireRate = fireRate;
            w.weaponHeatPerShot = heatPerShot;
            w.ammoPerMagazine = 0;
            w.reloadSeconds = 0f;
            w.shieldInteraction = shieldIx;
            w.hullInteraction = hullIx;
            w.requiresDeployedHardpoint = true;
            return w;
        }

        private static WeaponHardpoint EnsureHardpoint(
            Transform parent, string name, UndeployDefenseConfig undeploy,
            out WeaponController weapon, WeaponDefinition definition)
        {
            Transform t = parent.Find(name);
            GameObject go;
            if (t == null)
            {
                go = new GameObject(name);
                Undo.RegisterCreatedObjectUndo(go, name);
                go.transform.SetParent(parent, false);
                go.transform.localPosition = Vector3.zero;
                go.transform.localRotation = Quaternion.identity;
            }
            else
            {
                go = t.gameObject;
            }

            Transform muzzle = go.transform.Find("Muzzle");
            if (muzzle == null)
            {
                var mz = new GameObject("Muzzle");
                Undo.RegisterCreatedObjectUndo(mz, "Muzzle");
                mz.transform.SetParent(go.transform, false);
                mz.transform.localPosition = new Vector3(0f, 0f, 2f);
                mz.transform.localRotation = Quaternion.identity;
                muzzle = mz.transform;
            }

            var hp = GetOrAddComponent<WeaponHardpoint>(go);
            weapon = GetOrAddComponent<WeaponController>(go);

            Undo.RegisterCompleteObjectUndo(hp, "Hardpoint");
            Undo.RegisterCompleteObjectUndo(weapon, "Weapon");

            SetPrivate(hp, "undeployConfig", undeploy);
            SetPrivate(hp, "deployDuration", 0.5f);
            SetPrivate(hp, "undeployDuration", 0.35f);
            SetPrivate(hp, "verboseLogs", false);

            SetPrivate(weapon, "definition", definition);
            SetPrivate(weapon, "hardpoint", hp);
            SetPrivate(weapon, "muzzle", muzzle);
            SetPrivate(weapon, "infiniteAmmoForDebug", false);
            SetPrivate(weapon, "verboseLogs", false);

            return hp;
        }

        private static T GetOrAddComponent<T>(GameObject go) where T : Component
        {
            T c = go.GetComponent<T>();
            if (c == null)
            {
                c = Undo.AddComponent<T>(go);
            }

            return c;
        }

        private static void SetPrivate(Component target, string fieldName, Object value)
        {
            SerializedObject so = new SerializedObject(target);
            so.FindProperty(fieldName).objectReferenceValue = value;
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        private static void SetPrivate(Component target, string fieldName, float value)
        {
            SerializedObject so = new SerializedObject(target);
            so.FindProperty(fieldName).floatValue = value;
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        private static void SetPrivate(Component target, string fieldName, bool value)
        {
            SerializedObject so = new SerializedObject(target);
            so.FindProperty(fieldName).boolValue = value;
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        private static void SetPrivate(Component target, string fieldName, int value)
        {
            SerializedObject so = new SerializedObject(target);
            so.FindProperty(fieldName).intValue = value;
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        private static void SetPrivate(Component target, string fieldName, System.Enum value)
        {
            SerializedObject so = new SerializedObject(target);
            so.FindProperty(fieldName).enumValueIndex = (int)(object)value;
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        private static T GetOrCreateAsset<T>(string path, System.Func<T> factory) where T : ScriptableObject
        {
            T existing = AssetDatabase.LoadAssetAtPath<T>(path);
            if (existing != null)
            {
                return existing;
            }

            T asset = factory();
            AssetDatabase.CreateAsset(asset, path);
            EditorUtility.SetDirty(asset);
            return asset;
        }

        private static void EnsureFolderExists(string assetPath)
        {
            if (AssetDatabase.IsValidFolder(assetPath))
            {
                return;
            }

            string parent = Path.GetDirectoryName(assetPath)?.Replace("\\", "/") ?? "Assets";
            string leaf = Path.GetFileName(assetPath);
            if (!AssetDatabase.IsValidFolder(parent))
            {
                EnsureFolderExists(parent);
            }

            AssetDatabase.CreateFolder(parent, leaf);
        }
    }

    internal static class SerializedPropertyArrayExtensions
    {
        public static void SetArray(this SerializedProperty prop, Object[] refs)
        {
            if (prop == null || !prop.isArray)
            {
                return;
            }

            prop.arraySize = refs == null ? 0 : refs.Length;
            for (int i = 0; i < prop.arraySize; i++)
            {
                prop.GetArrayElementAtIndex(i).objectReferenceValue = refs[i];
            }
        }
    }
