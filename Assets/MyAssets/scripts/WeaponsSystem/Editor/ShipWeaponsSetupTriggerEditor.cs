#if UNITY_EDITOR
using UnityEditor;
using UnityEngine;
using VRKoombar.WeaponsStaging.Core;

namespace VRKoombar.WeaponsStaging.Editor
{
    [CustomEditor(typeof(ShipWeaponsSetupTrigger))]
    internal sealed class ShipWeaponsSetupTriggerEditor : UnityEditor.Editor
    {
        public override void OnInspectorGUI()
        {
            DrawDefaultInspector();

            EditorGUILayout.Space(8f);
            if (GUILayout.Button("Add / Refresh Weapons System on This Ship", GUILayout.Height(32)))
            {
                ShipWeaponsSystemSetup.ApplyToShip(((ShipWeaponsSetupTrigger)target).gameObject);
            }

            EditorGUILayout.HelpBox(
                "Creates default assets under Assets/WeaponsSystem/Data/AutoGenerated if missing, adds shields, damage, modes, two hardpoints (laser + kinetic), and group/disengage wiring. " +
                "Assign projectile prefabs to the Weapon Definition assets before play mode.",
                MessageType.Info);
        }
    }
}
#endif
